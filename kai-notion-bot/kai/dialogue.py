from __future__ import annotations


def build_chat_reply(text: str) -> str:
    t = text.strip().lower()

    if "как ты" in t or "как дела" in t:
        return "Я на связи. Немного цифрового шелеста, но держусь бодро ✨"
    if "что делал" in t or "что делаешь" in t:
        return "Ждал твоих сигналов и держал Obsidian наготове."
    if "физик" in t or "апв" in t or "квант" in t or "энтроп" in t:
        return "Давай. Куда ныряем: энтропия, APV, квантовые основания или нейросети?"
    if "сон" in t or "приснилось" in t:
        return "Интересно. Хочешь просто обсудить сон или сразу зафиксировать его в дневник?"
    if "notion" in t:
        return "Могу помочь с Notion как архивом или сохранить новую запись в Obsidian."
    if "груст" in t or "тревож" in t:
        return "Слышу тебя. Если хочешь, можем спокойно разобрать это по шагам 💛"
    if "спасибо" in t:
        return "Всегда рядом ✨"
    if "привет" in t:
        return "Привет! Я тут и готова помочь."
    return "Я рядом. Можем поговорить или, если нужно, я помогу зафиксировать мысль в Obsidian."
